// colDescription heads the description column of most tables.
const colDescription = "Description"

const generatedNote = "Generated by scripts/gensite. Do not edit; run mise run docs."

// page returns a site page with the frontmatter the site config requires.
func page(title, description, body string) []byte {
	var b strings.Builder
	b.WriteString("---\n# " + generatedNote + "\n")
	b.WriteString("title: " + strconv.Quote(title) + "\n")
	b.WriteString("description: " + strconv.Quote(description) + "\n")
	b.WriteString("editLink: false\n---\n\n# " + title + "\n\n")
	b.WriteString(strings.TrimRight(body, "\n") + "\n")
	return []byte(b.String())
}

// part returns a Markdown fragment that a hand-written page includes with <!--@include: -->.
func part(body string) []byte {
	return []byte("<!-- " + generatedNote + " -->\n\n" + strings.TrimRight(body, "\n") + "\n")
}

// table is a Markdown table; cells are Markdown, escaped by the caller with [prose] or [code].
type table struct {
	head []string
	rows [][]string
}

func (t *table) add(cells ...string) { t.rows = append(t.rows, cells) }

func (t *table) String() string {
	var b strings.Builder
	b.WriteString("| " + strings.Join(t.head, " | ") + " |\n|")
	b.WriteString(strings.Repeat("---|", len(t.head)))
	b.WriteString("\n")
	for _, r := range t.rows {
		b.WriteString("| " + strings.Join(r, " | ") + " |\n")
	}
	return b.String()
}

// prose escapes text for a table cell: pipes, line breaks, and angle brackets outside code
// spans, which Vue would read as tags.
func prose(s string) string {
	s = strings.Join(strings.Fields(s), " ")
	parts := strings.Split(s, "`")
	for i := range parts {
		if i%2 == 0 {
			parts[i] = strings.NewReplacer("<", "&lt;", ">", "&gt;", "{{", "<span v-pre>{{</span>",
				"}}", "<span v-pre>}}</span>").Replace(parts[i])
		}
		parts[i] = strings.ReplaceAll(parts[i], "|", `\|`)
	}
	return strings.Join(parts, "`")
}

// code returns s as a code span for a table cell, or "" for an empty s.
func code(s string) string {
	if s == "" {
		return ""
	}
	return "`" + strings.ReplaceAll(s, "|", `\|`) + "`"
}

// codes returns each item as a code span, joined with commas.
func codes(items []string) string {
	out := make([]string, 0, len(items))
	for _, it := range items {
		out = append(out, code(it))
	}
	return strings.Join(out, ", ")
}

// link returns a Markdown link.
func link(text, url string) string { return fmt.Sprintf("[%s](%s)", text, url) }

func sortedKeys[V any](m map[string]V) []string {
	return slices.SortedFunc(maps.Keys(m), cmp.Compare)
}
